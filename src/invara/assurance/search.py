@dataclass(frozen=True)
class SearchResult:
    status: str
    seed: int
    runs: int
    compared_runs: int
    unverifiable_runs: int
    shrink_runs: int
    elapsed_s: float
    corpus_size: int
    original: dict[str, Any] | None
    minimized: dict[str, Any] | None
    trace_digest: str
    reason: str

    def as_dict(self) -> dict[str, Any]:
        return {
            "status": self.status,
            "seed": self.seed,
            "runs": self.runs,
            "compared_runs": self.compared_runs,
            "unverifiable_runs": self.unverifiable_runs,
            "shrink_runs": self.shrink_runs,
            "elapsed_s": self.elapsed_s,
            "corpus_size": self.corpus_size,
            "original": dict(self.original) if self.original is not None else None,
            "minimized": dict(self.minimized) if self.minimized is not None else None,
            "trace_digest": self.trace_digest,
            "reason": self.reason,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "SearchResult":
        return cls(
            status=data["status"],
            seed=int(data["seed"]),
            runs=int(data["runs"]),
            compared_runs=int(data["compared_runs"]),
            unverifiable_runs=int(data["unverifiable_runs"]),
            shrink_runs=int(data["shrink_runs"]),
            elapsed_s=float(data["elapsed_s"]),
            corpus_size=int(data["corpus_size"]),
            original=dict(data["original"]) if data.get("original") is not None else None,
            minimized=dict(data["minimized"]) if data.get("minimized") is not None else None,
            trace_digest=data["trace_digest"],
            reason=data.get("reason", ""),
        )


def _candidates(seeds: Sequence[CorpusItem], prng: Prng, sequence_of_operations: bool) -> Iterator[tuple[Any, str, str]]:
    """Candidates as ``(input, description, seed id)``; a candidate's state is its seed's."""

    for seed in seeds:
        yield _copy(seed.input), f"seed:{seed.id}", seed.id
    for tier in range(_TIERS):
        for seed in seeds:
            for candidate, description in _tier_candidates(seed.input, tier):
                yield candidate, description, seed.id
    bases: list[tuple[Any, str]] = [(seed.input, seed.id) for seed in seeds]
    generated: list[tuple[Any, str]] = []
    while True:
        base, origin = prng.choice(generated) if generated and prng.random() < 0.3 else prng.choice(bases)
        candidate, description = mutate(base, prng, sequence_of_operations=sequence_of_operations)
        generated.append((candidate, origin))
        if len(generated) > 64:
            del generated[0]
        yield candidate, description, origin


def search(
    seeds: Sequence[CorpusItem],
    evaluate: Callable[[CorpusItem], Any],
    *,
    seed: int,
    max_runs: int,
    max_seconds: float,
    shrink_steps: int,
    clock: Callable[[], float] = time.monotonic,
    sequence_of_operations: bool = False,
) -> SearchResult:
    """Run the search. ``evaluate`` returns anything with ``status`` and ``mandatory_equivalent``."""

    prng = Prng(seed)
    started = clock()
    runs = compared = unverifiable = shrink_runs = 0
    trace: list[Any] = []
    original: dict[str, Any] | None = None
    minimized: dict[str, Any] | None = None
    # the initial state (seeded files, seeded rows) is part of the input
    # domain, so every candidate runs under the state of the seed it came from
    states = {item.id: dict(item.initial_state) for item in seeds}
    if seeds and max_runs > 0:
        for candidate, description, origin in _candidates(seeds, prng, sequence_of_operations):
            if runs >= max_runs or clock() - started >= max_seconds:
                break
            runs += 1
            trace.append(candidate)
            state = states.get(origin, {})
            outcome = evaluate(CorpusItem(id=f"search-{runs}", input=candidate, initial_state=dict(state)))
            if outcome.status != "compared":
                unverifiable += 1
                continue
            compared += 1
            if outcome.mandatory_equivalent:
                continue
            original = {
                "id": f"search-{runs}",
                "input": candidate,
                "derived_from": origin,
                "mutation": description,
                "size": _size(candidate),
            }
            if state:
                original["initial_state"] = dict(state)
            digest = getattr(outcome, "digest", None)
            if callable(digest):
                original["comparison_digest"] = digest()
            counter = [0]

            def reproduces(value: Any) -> bool:
                counter[0] += 1
                result = evaluate(CorpusItem(id=f"shrink-{counter[0]}", input=value, initial_state=dict(state)))
                return result.status == "compared" and not result.mandatory_equivalent

            smallest, steps = shrink(candidate, reproduces, max_steps=shrink_steps)
            shrink_runs = counter[0]
            minimized = {"id": "minimized", "input": smallest, "shrink_steps": steps, "size": _size(smallest)}
            if state:
                minimized["initial_state"] = dict(state)
            break
    elapsed = clock() - started
    trace_digest = content_digest({"seed": seed, "trace": trace})
    if original is not None:
        status, reason = DIVERGED, f"divergence found on run {original['id']} and minimized in {minimized['shrink_steps'] if minimized else 0} step(s)"
    elif compared == 0:
        status, reason = UNVERIFIABLE, "no candidate could be compared" if runs else "the search budget allowed no runs"
    else:
        status, reason = NO_DIVERGENCE_FOUND, f"{compared} candidate(s) compared without divergence; this is not a proof"
    return SearchResult(
        status=status,
        seed=seed,
        runs=runs,
        compared_runs=compared,
        unverifiable_runs=unverifiable,
        shrink_runs=shrink_runs,
        elapsed_s=elapsed,
        corpus_size=len(seeds),
        original=original,
        minimized=minimized,
        trace_digest=trace_digest,
        reason=reason,
    )
